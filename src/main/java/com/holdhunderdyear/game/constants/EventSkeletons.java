    /** 骨架工厂：truthProb 按来源带状取基准，tickRange 按模式推导——避免逐条手写走样。 */
    private static EventSkeleton sk(String code, Scope scope, Source source, double weight,
                                    TargetSelector target, ImpactPattern pattern,
                                    double lo, double hi, List<Variant> variants, String... followups) {
        return sk(code, scope, source, Set.of(), weight, target, pattern, lo, hi, variants, followups);
    }

    /** 骨架工厂（带纪元）：见重载；eras 非空限定可用纪元。 */
    private static EventSkeleton sk(String code, Scope scope, Source source, Set<EraCode> eras, double weight,
                                    TargetSelector target, ImpactPattern pattern,
                                    double lo, double hi, List<Variant> variants, String... followups) {
        double truthProb = switch (source) {
            case AUTHORITY -> 1.0;
            case MEDIA -> 0.80;
            case RUMOR -> 0.45;
            case INSIDER -> 0.70;
            default -> throw new IllegalArgumentException("unsupported source in skeletons: " + source);
        };
        int[] ticks = switch (pattern) {
            case SLOW_DRIFT -> new int[]{10, 31};
            case BUY_RUMOR -> new int[]{10, 21};
            default -> new int[]{1, 1};
        };
        return new EventSkeleton(code, scope, source, eras, weight, target, pattern,
                new double[]{lo, hi}, ticks, truthProb, variants, List.of(followups));
    }

    /** 变体（通用，sector=null）。 */
    private static Variant v(String title, String text) {
        return new Variant(null, title, text);
    }

    /** 变体（SECTOR，sector 必须匹配 StockDefs.ALL_SECTORS）。 */
    private static Variant v(String sector, String title, String text) {
        return new Variant(sector, title, text);
    }
